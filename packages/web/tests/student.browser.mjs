import assert from 'node:assert/strict';
import process from 'node:process';
import console from 'node:console';
import { URL } from 'node:url';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import { studentFixture, dated } from '../src/student-fixture.ts';

// Playwright is supplied by the operator, without changing workspace dependencies.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const require = createRequire(new URL('../../server/package.json', import.meta.url));
process.env.FIRESTORE_EMULATOR_HOST = '127.0.0.1:8085';
const { initializeApp, deleteApp } = require('firebase-admin/app');
const { getFirestore } = require('firebase-admin/firestore');
const app = initializeApp({ projectId: 'demo-kadai-hisho' }, 'student-browser');
const db = getFirestore(app);
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 960 } });
page.setDefaultTimeout(15000);
const errors = [];
const evidenceDir = process.env.ARTIFACT_EVIDENCE_DIR || '/tmp/kadai-i20-evidence';
page.on('pageerror', () => errors.push('browser-error'));
let student;
try {
  await page.goto('http://127.0.0.1:5176/student');
  await page.getByRole('button', { name: 'Googleでログイン' }).waitFor();
  const uid = await page.evaluate(async () => {
    const { firebase } = await import('/src/firebase.ts');
    const source = await (await globalThis.fetch('/src/firebase.ts')).text();
    const sdk = await import(source.match(/from "([^"]*firebase_auth[^"]*)"/)[1]);
    const user = await sdk.signInAnonymously(firebase.auth);
    return user.user.uid;
  });
  student = db.collection('students').doc(uid);
  await page.getByText('まだ課題がありません。', { exact: false }).waitFor();
  const data = studentFixture();
  const batch = db.batch();
  data.courses.forEach((course, i) => batch.set(student.collection('courses').doc(`c${i}`), course));
  data.assignments.forEach((item, i) => batch.set(student.collection('assignments').doc(`a${i}`), item));
  data.fetchStates.forEach(state => batch.set(student.collection('fetchStates').doc(state.system), { ...state, studentId: uid }));
  await batch.commit();
  const cells = page.locator('.course-cell').filter({ hasText: '架空の線形代数' });
  await cells.first().waitFor();
  assert.equal(await cells.count(), 2);
  assert.match(await cells.first().innerText(), /11\/10（日付のみ）/);
  assert.doesNotMatch(await page.locator('.course-cell').filter({ hasText: '架空の別大学の授業' }).innerText(), /レポート/);
  assert.equal(await page.getByText('授業を押すと、課題が開きます。', { exact: true }).count(), 0);
  assert.equal(await page.locator('.upcoming .review').count(), 0);
  await cells.first().click();
  const panel = page.getByRole('complementary', { name: '架空の線形代数の課題' });
  await panel.getByRole('heading', { name: 'レポートA', exact: true }).waitFor();
  assert.doesNotMatch(await panel.innerText(), /出せました|取り消されました/);
  await panel.getByText('今回、締切を読めませんでした。', { exact: false }).waitFor();
  await panel.getByText('終了した課題', { exact: true }).click();
  assert.match(await panel.innerText(), /出せました/);
  assert.match(await panel.innerText(), /取り消されました/);
  await panel.getByText('書いてあったこと', { exact: true }).first().click();
  assert.equal(await panel.getByRole('link', { name: 'LMSで見る ›' }).first().getAttribute('href'), 'https://example.invalid/task');
  await page.getByText('から更新がありません。', { exact: false }).waitFor();
  await mkdir(evidenceDir, { recursive: true });
  await page.screenshot({ path: `${evidenceDir}/student-wide.png`, fullPage: true });
  await student.collection('assignments').doc('a0').update({ 'officialDeadline.deadline': dated('2026-11-08') });
  await cells.first().getByText('11/8（日付のみ）', { exact: true }).waitFor();
  assert.match(await page.locator('.upcoming li').first().innerText(), /レポートB/);
  assert.match(await panel.innerText(), /11\/8（日付のみ）/);
  await student.collection('assignments').doc('a0').update({ submission: 'submitted' });
  await cells.first().getByText('レポートA', { exact: true }).waitFor();
  await page.evaluate(async () => {
    const { firebase } = await import('/src/firebase.ts');
    const source = await (await globalThis.fetch('/src/firebase.ts')).text();
    await (await import(source.match(/from "([^"]*firebase_firestore[^"]*)"/)[1])).disableNetwork(firebase.db);
  });
  await page.getByText('接続を確かめています。', { exact: false }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => globalThis.document.documentElement.scrollWidth <= globalThis.innerWidth), true);
  assert.ok((await page.locator('.timetable td').first().boundingBox()).width >= 115);
  await page.screenshot({ path: `${evidenceDir}/student-narrow.png`, fullPage: true });
  await panel.getByRole('button', { name: '閉じる' }).click();
  await page.getByRole('button', { name: '架空の集中講義' }).click();
  await page.getByText('この授業の課題はまだありません。').waitFor();
  await page.getByRole('button', { name: 'ログアウト' }).click();
  await page.getByRole('button', { name: 'Googleでログイン' }).waitFor();
  assert.doesNotMatch(await page.locator('body').innerText(), /レポート|架空の線形代数/);
  assert.deepEqual(errors, []);
  console.log('PASS C18/C19/C20: empty, timetable, course panel, live deadline/submission, review, stale, offline, narrow, logout');
} finally {
  await browser.close();
  if (student) await db.recursiveDelete(student);
  await deleteApp(app);
}
